#!/usr/bin/env node
/* Embeds examples/*.md into js/core/samples.js, so the app works without fetch (file://, offline).
 * Run after editing an example: node tools/build-samples.js */
'use strict';
const fs = require('fs');
const path = require('path');
const F = require('../js/core/format.js');

const dir = path.join(__dirname, '..', 'examples');
const ORDER = ['courants-pedagogiques', 'ethiques-ia'];
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.md'))
  .sort((a, b) => (ORDER.indexOf(a.slice(0, -3)) + 1 || 99) - (ORDER.indexOf(b.slice(0, -3)) + 1 || 99));
const list = files.map((f) => {
  const md = fs.readFileSync(path.join(dir, f), 'utf8').replace(/\r\n?/g, '\n');
  const { doc, warnings } = F.parse(md);
  if (warnings.length) console.warn(f + ':\n  ' + warnings.map((w) => w.message).join('\n  '));
  return { id: f.slice(0, -3), file: 'examples/' + f, title: doc.meta.title, lang: doc.meta.lang, markdown: md };
});
const out = '/*! Generated by tools/build-samples.js from examples/*.md: do not edit by hand. */\n' +
  '(function (PG) {\n  \'use strict\';\n  PG.samples = ' + JSON.stringify(list, null, 2) + ';\n})(window.PG = window.PG || {});\n';
fs.writeFileSync(path.join(__dirname, '..', 'js', 'core', 'samples.js'), out);
console.log('js/core/samples.js: ' + list.map((s) => s.id).join(', '));
